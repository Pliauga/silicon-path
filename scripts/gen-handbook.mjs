// Generates src/lib/content/handbook-meta.ts from chapter frontmatter.
//
// The rail and the drawer need the chapter list on every page, so they must not
// import `handbook.ts`: that module eager-imports every compiled chapter. This
// manifest is the lightweight equivalent, and a unit test keeps it in sync with
// the MDX frontmatter it is generated from.
// Run with: node scripts/gen-handbook.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const chaptersDir = join(root, 'src', 'content', 'handbook');
const outFile = join(root, 'src', 'lib', 'content', 'handbook-meta.ts');

/** Reads the small YAML subset used by chapter frontmatter. */
function readFrontmatter(text) {
	const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
	if (!match) throw new Error('Missing frontmatter');
	const fields = {};
	for (const line of match[1].split(/\r?\n/)) {
		const pair = line.match(/^(\w+):\s*(.*)$/);
		if (!pair) continue;
		let value = pair[2].trim();
		if (
			(value.startsWith("'") && value.endsWith("'")) ||
			(value.startsWith('"') && value.endsWith('"'))
		) {
			value = value.slice(1, -1);
		}
		fields[pair[1]] = value;
	}
	return fields;
}

const chapters = readdirSync(chaptersDir)
	.filter((file) => file.endsWith('.mdx'))
	.sort()
	.map((file) => {
		const fields = readFrontmatter(readFileSync(join(chaptersDir, file), 'utf8'));
		const slug = file.replace(/\.mdx$/, '');
		return {
			slug,
			id: fields.id ?? slug,
			title: fields.title ?? slug,
			estimatedMinutes: Number(fields.estimatedMinutes ?? 30),
			hasExercise: fields.hasExercise === 'true'
		};
	});

const body = chapters
	.map(
		(chapter) => `	{
		slug: '${chapter.slug}',
		id: '${chapter.id.replace(/'/g, "\\'")}',
		title: '${chapter.title.replace(/'/g, "\\'")}',
		estimatedMinutes: ${chapter.estimatedMinutes},
		hasExercise: ${chapter.hasExercise}
	}`
	)
	.join(',\n');

writeFileSync(
	outFile,
	`// Generated by scripts/gen-handbook.mjs — do not edit by hand.
// Run \`node scripts/gen-handbook.mjs\` after adding or renaming a chapter.

/** The frontmatter a chapter must expose (mirrors the loader's contract). */
export interface HandbookChapterMeta {
	slug: string;
	id: string;
	title: string;
	estimatedMinutes: number;
	hasExercise: boolean;
}

/** Every chapter, in reading order (numeric filename prefix). */
export const handbookMeta: HandbookChapterMeta[] = [
${body}
];
`
);

console.log(`Wrote ${chapters.length} chapters to src/lib/content/handbook-meta.ts`);